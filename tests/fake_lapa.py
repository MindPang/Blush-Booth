from pathlib import Path

import cv2
import numpy as np


def make_ring(cx, cy, rx, ry, n_half):
    """Closed outline: start at the left end, go along the top to the right end, then back along the bottom."""
    pts = []
    for k in range(n_half + 1):
        a = np.pi - np.pi * k / n_half
        pts.append((cx + rx * np.cos(a), cy - ry * np.sin(a)))
    for k in range(1, n_half):
        a = -np.pi * k / n_half
        pts.append((cx + rx * np.cos(a), cy - ry * np.sin(a)))
    return pts


def template():
    """106 points of a symmetric cartoon face, x in about [-0.5, 0.5], y down."""
    p = []
    for k in range(33):
        a = np.pi * k / 32
        p.append((-0.5 * np.cos(a), -0.05 + 0.6 * np.sin(a)))
    xs = np.linspace(-0.42, -0.10, 5)                      # right brow (image left) 33-37 upper, outer->inner
    p += [(x, -0.33 - 0.04 * np.sin(np.pi * (x + 0.42) / 0.32)) for x in xs]
    p += [(x, -0.27) for x in np.linspace(-0.12, -0.40, 4)]
    p += [(-x, y) for x, y in p[37:32:-1]]
    p += [(-x, y) for x, y in p[41:37:-1]]
    p += [(0.0, y) for y in np.linspace(-0.18, 0.08, 4)]
    p += [(x, 0.14 + 0.06 * (abs(x) / 0.13)) for x in np.linspace(-0.13, 0.13, 11)][::1]
    p += make_ring(-0.22, -0.15, 0.09, 0.04, 4)
    p.append((-0.22, -0.15))
    p += make_ring(0.22, -0.15, 0.09, 0.04, 4)
    p.append((0.22, -0.15))
    p += make_ring(0.0, 0.33, 0.17, 0.07, 6)
    p += make_ring(0.0, 0.33, 0.12, 0.025, 4)
    p += [(-0.22, -0.15), (0.22, -0.15)]
    a = np.array(p, dtype=np.float64)
    assert a.shape == (106, 2), a.shape
    return a


def draw_sample(rng, size=(360, 300)):
    """Return (image BGR, points (106, 2), label map) of one random cartoon face."""
    H, W = size
    t = template()
    scale = rng.uniform(0.35, 0.5) * W
    ang = np.radians(rng.uniform(-15, 15))
    R = np.array([[np.cos(ang), -np.sin(ang)], [np.sin(ang), np.cos(ang)]])
    c = np.array([W / 2 + rng.uniform(-0.08, 0.08) * W, H / 2 + rng.uniform(-0.05, 0.1) * H])
    pts = (t * scale) @ R.T + c + rng.normal(0, 0.6, t.shape)
    img = np.full((H, W, 3), rng.randint(40, 200, 3), np.uint8)
    img = np.clip(img + rng.normal(0, 8, img.shape), 0, 255).astype(np.uint8)
    lab = np.zeros((H, W), np.uint8)

    def poly(idx, cls, colour):
        q = np.round(pts[list(idx)]).astype(np.int32)
        cv2.fillPoly(lab, [q], int(cls))
        cv2.fillPoly(img, [q], colour)

    top = pts[:, 1].min() - 0.34 * (pts[:, 1].max() - pts[:, 1].min())
    head_c = (pts[0] + pts[32]) / 2
    rx = np.linalg.norm(pts[32] - pts[0]) / 2
    hair = cv2.ellipse2Poly((int(head_c[0]), int(head_c[1])), (int(rx * 1.15), int(head_c[1] - top + 15)),
                            int(np.degrees(ang)), 180, 360, 5)
    cv2.fillPoly(lab, [hair], 10)
    cv2.fillPoly(img, [hair], (30, 30, 40))
    forehead = cv2.ellipse2Poly((int(head_c[0]), int(head_c[1])), (int(rx), int(head_c[1] - top)),
                                int(np.degrees(ang)), 180, 360, 10)
    face = np.vstack([np.round(pts[:33]).astype(np.int32), forehead])
    cv2.fillPoly(lab, [cv2.convexHull(face)], 1)
    cv2.fillPoly(img, [cv2.convexHull(face)], (120, 160, 210))
    poly(range(33, 42), 2, (40, 60, 90))      # points 33-41 (image left) -> class 2, as in LaPa
    poly(range(42, 51), 3, (40, 60, 90))
    poly(list(range(51, 55)) + list(range(65, 54, -1)), 6, (110, 140, 200))
    poly(range(66, 74), 4, (250, 250, 250))   # points 66-73 (image left) -> class 4, as in LaPa
    poly(range(75, 83), 5, (250, 250, 250))
    poly(range(84, 96), 7, (80, 60, 200))
    lower = list(range(90, 96)) + [84, 96, 103, 102, 101, 100]
    poly(lower, 9, (70, 50, 170))
    poly(range(96, 104), 8, (40, 20, 60))
    for k in (104, 105):
        cv2.circle(img, tuple(int(v) for v in np.round(pts[k])), 3, (30, 20, 10), -1)
    return img, pts, lab


def make_fake_lapa(root, counts=None, seed=0):
    """Write a fake LaPa folder with a few cartoon faces per split."""
    if counts is None:
        counts = {"train": 24, "val": 8, "test": 8}
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    (root / "FAKE_DATA.txt").write_text("Generated by tests/fake_lapa.py for code tests. Not LaPa. Results on it "
                                        "are meaningless.\n")
    rng = np.random.RandomState(seed)
    for split, n in counts.items():
        for sub in ("images", "labels", "landmarks"):
            (root / split / sub).mkdir(parents=True, exist_ok=True)
        for i in range(n):
            img, pts, lab = draw_sample(rng)
            name = f"fake_{split}_{i:04d}"
            cv2.imwrite(str(root / split / "images" / f"{name}.jpg"), img)
            cv2.imwrite(str(root / split / "labels" / f"{name}.png"), lab)
            (root / split / "landmarks" / f"{name}.txt").write_text(
                "106\n" + "\n".join(f"{x:.3f} {y:.3f}" for x, y in pts) + "\n")
    return root
